"""Build the theme content map from <id>.points.csv (part E) joined with <id>.coder1.csv (roles).

Run:  py themes.py   -> writes ../THEMES_RESULTS.md: per theme, argument-mode shares, and every paragraph's
point in reading order per thesis (closest four first), with its role and argument mode.
"""
import csv, sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "measures"))
from measure import UNITS, CLOSEST4, BORE2

THEMES = ["uncertainty", "markets", "physical", "methods", "investment", "system-models", "contribution", "search", "background", "other"]
ARGS = ["finding", "claim-evidence", "claim-backup", "reasoning", "description"]


def load(tid):
    roles = {}
    p = HERE / f"{tid}.coder1.csv"
    if p.exists():
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            roles[r["para"].strip()] = {k: (v or "").strip() for k, v in r.items()}
    pts = []
    p = HERE / f"{tid}.points.csv"
    if p.exists():
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            r = {k: (v or "").strip() for k, v in r.items()}
            r["thesis"] = tid
            r.update({f"r_{k}": v for k, v in roles.get(r["para"], {}).items()})
            pts.append(r)
    return pts


def pct(n, d):
    return f"{100 * n / d:.0f} %" if d else "–"


def main():
    rows = [r for tid in UNITS for r in load(tid)]
    present = sorted({r["thesis"] for r in rows})
    order = [t for t in CLOSEST4 if t in present] + [t for t in present if t not in CLOSEST4]
    groups = [(f"All ({len(present)})", present), ("Closest four", [t for t in CLOSEST4 if t in present]), ("Bore two", [t for t in BORE2 if t in present])]
    out = ["# Theme content map", "", f"From `coding/<id>.points.csv` (part E) for {len(present)} reviews, {len(rows)} paragraphs, joined with the role coding. Generated by `themes.py`.", ""]

    out += ["## How points are argued, by group", "", "| Argument | " + " | ".join(g for g, _ in groups) + " |", "|---|" + "---|" * len(groups)]
    for a in ARGS:
        out.append(f"| {a} | " + " | ".join(pct(sum(1 for r in rows if r['thesis'] in ids and r['argument'] == a), sum(1 for r in rows if r['thesis'] in ids)) for _, ids in groups) + " |")
    out += ["", "| Works whose finding is reported | " + " | ".join(g for g, _ in groups) + " |", "|---|" + "---|" * len(groups)]
    for s in ["0", "1", "2", "3+"]:
        out.append(f"| {s} | " + " | ".join(pct(sum(1 for r in rows if r['thesis'] in ids and r['source_use'] == s), sum(1 for r in rows if r['thesis'] in ids)) for _, ids in groups) + " |")
    out.append("")

    out += ["## How points are argued, by theme (all reviews)", "", "| Theme | n | " + " | ".join(ARGS) + " | findings from 3+ works |", "|---|---|" + "---|" * (len(ARGS) + 1)]
    for t in THEMES:
        rs = [r for r in rows if r["theme"] == t]
        if not rs:
            continue
        out.append(f"| {t} | {len(rs)} | " + " | ".join(pct(sum(1 for r in rs if r["argument"] == a), len(rs)) for a in ARGS) + f" | {pct(sum(1 for r in rs if r['source_use'] == '3+'), len(rs))} |")
    out.append("")

    for t in THEMES:
        rs = [r for r in rows if r["theme"] == t]
        if not rs:
            continue
        out += [f"## Theme: {t} ({len(rs)} paragraphs in {len({r['thesis'] for r in rs})} reviews)", ""]
        for tid in order:
            mine = [r for r in rs if r["thesis"] == tid]
            if not mine:
                continue
            tag = " (closest)" if tid in CLOSEST4 else ""
            out.append(f"**{tid}{tag}**")
            for r in mine:
                out.append(f"- [{r['para']} {r.get('r_role', '?')} · {r['argument']} · {r['source_use']} works] {r['point']}")
            out.append("")
    txt = "\n".join(out)
    (HERE.parent / "THEMES_RESULTS.md").write_text(txt + "\n", encoding="utf-8")
    print(txt[:3000])


if __name__ == "__main__":
    main()
