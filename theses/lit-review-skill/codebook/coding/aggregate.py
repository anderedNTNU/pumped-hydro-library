"""Aggregate the paragraph codings (<id>.coder1.csv) into shares per group, for the skill.

Run:  py aggregate.py   -> writes ../CODING_RESULTS.md and prints it.
Groups: all reviews, the closest four, the two Bore theses (D-002 tie-break order).
"""
import csv, sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "measures"))
from measure import UNITS, CLOSEST4, BORE2

FIELDS = ["role", "b1_opener", "b2_backing", "b3_limitation", "b4_compare", "b5_consequence", "b6_link", "b7_closer", "b8_number"]
ROLES = ["OPEN", "CLAIM", "STUDY", "GROUP", "COMPARE", "CRITIQUE", "SYNTH", "GAP"]
ATTRS = ["aim", "method", "case", "markets", "uncertainty", "horizon", "finding", "number", "limitation", "relation", "use"]


def load_all():
    rows = []
    for tid in UNITS:
        p = HERE / f"{tid}.coder1.csv"
        if not p.exists():
            print("missing", p.name)
            continue
        with open(p, encoding="utf-8-sig") as f:
            for r in csv.DictReader(f):
                r = {k: (v or "").strip() for k, v in r.items()}
                r["thesis"] = tid
                rows.append(r)
    return rows


def pct(n, d):
    return f"{100 * n / d:.0f} %" if d else "–"


def share_table(rows, groups, field, values, title):
    out = [f"### {title}", "", "| Value | " + " | ".join(g for g, _ in groups) + " |", "|---|" + "---|" * len(groups)]
    for v in values:
        cells = []
        for _, ids in groups:
            rs = [r for r in rows if r["thesis"] in ids]
            cells.append(pct(sum(1 for r in rs if r[field] == v), len(rs)))
        out.append(f"| {v} | " + " | ".join(cells) + " |")
    out.append("")
    return out


def main():
    rows = load_all()
    present = sorted({r["thesis"] for r in rows})
    groups = [(f"All ({len(present)})", present), ("Closest four", [t for t in CLOSEST4 if t in present]), ("Bore two", [t for t in BORE2 if t in present])]
    out = ["# Paragraph coding results", "", f"From `coding/<id>.coder1.csv` for {len(present)} reviews, {len(rows)} paragraphs (codebook v1.1). "
           "Shares are of paragraphs unless stated. Generated by `aggregate.py`.", ""]
    out += [f"Paragraphs per group: " + ", ".join(f"{g} = {sum(1 for r in rows if r['thesis'] in ids)}" for g, ids in groups), ""]

    out += share_table(rows, groups, "role", ROLES, "Role of the paragraph")
    out += share_table(rows, groups, "b1_opener", ["claim", "study", "transition", "question"], "B1 What the first sentence does")
    out += share_table(rows, groups, "b2_backing", ["0", "1", "2", "3+"], "B2 Works backing the main point")
    out += share_table(rows, groups, "b3_limitation", ["none", "named", "group"], "B3 Limitation stated")
    out += share_table(rows, groups, "b4_compare", ["yes"], "B4 Two named studies compared")
    out += share_table(rows, groups, "b5_consequence", ["yes"], "B5 A consequence is drawn")
    out += share_table(rows, groups, "b6_link", ["none", "implicit", "explicit"], "B6 Link to the thesis")
    out += share_table(rows, groups, "b7_closer", ["consequence", "study", "claim", "limitation", "pointer"], "B7 What the last sentence does")
    out += share_table(rows, groups, "b8_number", ["yes"], "B8 A number with a unit or %")

    # role by position in the section
    out += ["### Role by position in its section (all reviews)", "", "| Position | " + " | ".join(ROLES) + " | n |", "|---|" + "---|" * (len(ROLES) + 1)]
    for pos in ["first", "middle", "last", "only"]:
        rs = [r for r in rows if r["c1_position"] == pos]
        out.append(f"| {pos} | " + " | ".join(pct(sum(1 for r in rs if r["role"] == ro), len(rs)) for ro in ROLES) + f" | {len(rs)} |")
    out.append("")
    out += ["### Role by position in its section (closest four)", "", "| Position | " + " | ".join(ROLES) + " | n |", "|---|" + "---|" * (len(ROLES) + 1)]
    for pos in ["first", "middle", "last", "only"]:
        rs = [r for r in rows if r["c1_position"] == pos and r["thesis"] in CLOSEST4]
        out.append(f"| {pos} | " + " | ".join(pct(sum(1 for r in rs if r["role"] == ro), len(rs)) for ro in ROLES) + f" | {len(rs)} |")
    out.append("")

    # structure by role (all)
    out += ["### Structure by role (all reviews): share of paragraphs of that role with …", "", "| Role | n | opens with claim | 3+ works | limitation (any) | compares | consequence | links to thesis | ends on consequence | number |", "|---|---|---|---|---|---|---|---|---|---|"]
    for ro in ROLES:
        rs = [r for r in rows if r["role"] == ro]
        n = len(rs)
        if not n:
            continue
        out.append(f"| {ro} | {n} | {pct(sum(r['b1_opener']=='claim' for r in rs), n)} | {pct(sum(r['b2_backing']=='3+' for r in rs), n)} | {pct(sum(r['b3_limitation']!='none' for r in rs), n)} | {pct(sum(r['b4_compare']=='yes' for r in rs), n)} | {pct(sum(r['b5_consequence']=='yes' for r in rs), n)} | {pct(sum(r['b6_link']!='none' for r in rs), n)} | {pct(sum(r['b7_closer']=='consequence' for r in rs), n)} | {pct(sum(r['b8_number']=='yes' for r in rs), n)} |")
    out.append("")

    # D: attributes per study mention
    out += ["### D What a paragraph reports about a study (share of study mentions)", "", "| Attribute | " + " | ".join(g for g, _ in groups) + " |", "|---|" + "---|" * len(groups)]
    mentions = defaultdict(list)
    for r in rows:
        s = r.get("studies", "")
        if not s:
            continue
        for item in s.split(";"):
            if ":" not in item:
                continue
            work, attrs = item.split(":", 1)
            mentions[r["thesis"]].append({a.strip().lower() for a in attrs.split(",") if a.strip()})
    for a in ATTRS:
        cells = []
        for _, ids in groups:
            ms = [m for t in ids for m in mentions.get(t, [])]
            cells.append(pct(sum(1 for m in ms if a in m), len(ms)))
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    cells = []
    for _, ids in groups:
        ms = [m for t in ids for m in mentions.get(t, [])]
        cells.append(f"{(sum(len(m) for m in ms) / len(ms)):.1f} (n={len(ms)})" if ms else "–")
    out.append("| **attributes per mention (mean)** | " + " | ".join(cells) + " |")
    out.append("")

    # per thesis role counts
    out += ["### Roles per thesis", "", "| Thesis | n | " + " | ".join(ROLES) + " |", "|---|---|" + "---|" * len(ROLES)]
    for t in present:
        rs = [r for r in rows if r["thesis"] == t]
        c = Counter(r["role"] for r in rs)
        out.append(f"| {t} | {len(rs)} | " + " | ".join(str(c.get(ro, 0)) for ro in ROLES) + " |")
    out.append("")
    txt = "\n".join(out)
    (HERE.parent / "CODING_RESULTS.md").write_text(txt + "\n", encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
