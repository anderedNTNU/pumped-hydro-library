"""Contrast set: the reference reviews against Claude-written drafts (the gap table and the two-way word lists).

Run:  py gaps.py <draft.txt> [<draft.txt> ...]   (plain-text drafts, e.g. rendered from .tex by profile_draft)
Writes GAPS.md: (1) every metric, closest-four median and range vs each draft; (2) words the drafts use more than
twice as often as the corpus (at least 3 occurrences); (3) words the corpus uses at least 0.5 per 1000 words that
the drafts use less than a third as often.
"""
import csv, json, re, statistics as st, sys
from collections import Counter
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from measure import UNITS, CLOSEST4, SEG, in_unit, words, citations, NUMBER_UNIT, HEDGES, CONNECT, SELF, AUTHOR_START, rhythm
from profile_draft import paragraphs, sentences

HERE = Path(__file__).resolve().parent
STOP = set("the of and to in a is are for that as with by on be this it from or an which can at their these such its has have was were also than into when more not but et al e g i we our they them there here these those where who whom whose what if then so than over under between both each other some any all may might would could should".split())
CIT = re.compile(r"\([^()]*?(?:19|20)\d{2}[a-z]?[^()]*\)|\[[^\]]*\]")


def tokens(text):
    text = CIT.sub(" ", text)
    return [w.lower() for w in re.findall(r"[A-Za-zÆØÅæøå][\w'’\-]+", text) if len(w) > 2 and w.lower() not in STOP]


def main():
    units = list(csv.DictReader(open(HERE / "units.csv", encoding="utf-8")))
    corpus_text = []
    for tid, u in UNITS.items():
        recs = [json.loads(l) for l in open(SEG / f"{tid}.jsonl", encoding="utf-8")]
        corpus_text.append(" ".join(r["text"] for r in recs if in_unit(r, u)))
    corpus = " ".join(corpus_text)
    cw = words(corpus)
    cfreq = Counter(tokens(corpus))
    # document frequency: in how many reviews a word occurs; topic words sit in few reviews, register words in many
    docfreq = Counter()
    for t in corpus_text:
        for w in set(tokens(t)):
            docfreq[w] += 1
    GENERAL = {w for w, d in docfreq.items() if d >= 7}
    keys = [k for k in units[0].keys() if k not in ("thesis", "closeness", "style", "thesis_words", "review_words", "paragraphs", "sections_l2", "sections_l3", "leaf_sections", "words_per_leaf", "works", "words_per_work")]
    out = ["# Gaps between the reference reviews and Claude-written drafts", "", "Generated by `gaps.py`. Closest-four median [min–max] against each draft; a gap is marked when the draft lies outside the range.", ""]
    drafts = {}
    for p in sys.argv[1:]:
        t = Path(p).read_text(encoding="utf-8", errors="ignore")
        drafts[Path(p).stem] = t
    # metric table
    out += ["## Metrics", "", "| Metric | Closest four | " + " | ".join(drafts) + " |", "|---|---|" + "---|" * len(drafts)]
    dm = {}
    for name, t in drafts.items():
        paras = paragraphs(t); full = " ".join(paras); nw = words(full)
        stexts = [s for p in paras for s in sentences(p)]
        ncit = 0; narr = 0; nworks = set(); pw = []; a0 = 0; nocite = 0; selfref = 0; numbers = 0
        for p in paras:
            n1, n2, wk = citations(p, "author-year"); ncit += n1 + n2; narr += n1; nworks |= wk
            pw.append(words(p)); a0 += bool(AUTHOR_START.match(p)); nocite += (len(wk) == 0); selfref += bool(SELF.search(p)); numbers += len(NUMBER_UNIT.findall(p))
        sw = [words(s) for s in stexts]
        m = {"share_pct": "", "cit_per_100_words": round(100 * ncit / nw, 2), "narrative_share_pct": round(100 * narr / max(1, ncit)),
             "median_par_words": st.median(pw), "median_sent_words": st.median(sw) if sw else 0,
             "share_sent_over_35": round(100 * sum(1 for x in sw if x > 35) / max(1, len(sw)), 1),
             "pars_starting_with_author_pct": round(100 * a0 / len(paras)), "pars_with_self_reference_pct": round(100 * selfref / len(paras)),
             "pars_without_citation_pct": round(100 * nocite / len(paras)), "numbers_with_unit_per_1000w": round(1000 * numbers / nw, 1),
             "hedges_per_1000w": round(1000 * len(HEDGES.findall(full)) / nw, 1), "connectors_per_1000w": round(1000 * len(CONNECT.findall(full)) / nw, 1)}
        m.update(rhythm(stexts, full, nw))
        dm[name] = (m, full, nw)
    for k in keys:
        vals = [float(u[k]) for u in units if u["thesis"] in CLOSEST4 and u[k] != ""]
        if not vals:
            continue
        lo, med, hi = min(vals), st.median(vals), max(vals)
        cells = []
        for name in drafts:
            v = dm[name][0].get(k, "")
            if v == "":
                cells.append("–"); continue
            flag = "" if lo <= float(v) <= hi else (" ↓" if float(v) < lo else " ↑")
            cells.append(f"{v:g}{flag}")
        out.append(f"| {k} | {med:g} [{lo:g}–{hi:g}] | " + " | ".join(cells) + " |")
    out.append("")
    # word lists
    for name in drafts:
        full, nw = dm[name][1], dm[name][2]
        dfreq = Counter(tokens(full))
        over = []
        for w, n in dfreq.items():
            if n < 3 or docfreq.get(w, 0) < 3:   # ignore topic words that only our drafts use
                continue
            dr = 1000 * n / nw; cr = 1000 * cfreq.get(w, 0) / cw
            if dr > 2 * max(cr, 0.05):
                over.append((dr / max(cr, 0.05), w, dr, cr, n))
        under = []
        for w, n in cfreq.items():
            cr = 1000 * n / cw
            if cr < 0.5 or w not in GENERAL:      # only words used across most reviews (register, not topic)
                continue
            dr = 1000 * dfreq.get(w, 0) / nw
            if dr < cr / 3:
                under.append((cr, w, cr, dr))
        out += [f"## Words {name} uses more than twice as often as the reviews (at least 3 times)", "",
                ", ".join(f"{w} ({dr:.1f} vs {cr:.1f})" for _, w, dr, cr, n in sorted(over, reverse=True)[:40]), "",
                f"## Words the reviews use (≥ 0.5 per 1000) that {name} uses less than a third as often", "",
                ", ".join(f"{w} ({cr:.1f} vs {dr:.1f})" for _, w, cr, dr in sorted(under, reverse=True)[:40]), ""]
    (HERE / "GAPS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
