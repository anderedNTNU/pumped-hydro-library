"""Phrasing patterns of the reference reviews, by paragraph role (no sentences copied: openers are
cut to their first 4-6 words, n-grams are 3-4 words). Output: PHRASING.md."""
import csv, json, re, sys
from collections import Counter, defaultdict
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from measure import UNITS, CLOSEST4, SEG, in_unit
HERE = Path(__file__).resolve().parent
COD = HERE.parent / "codebook" / "coding"
texts = {}
for tid, units in UNITS.items():
    recs = [json.loads(l) for l in open(SEG / f"{tid}.jsonl", encoding="utf-8")]
    paras = [r["text"] for r in recs if in_unit(r, units)]
    roles = {}
    p = COD / f"{tid}.coder1.csv"
    if p.exists():
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            roles[int(r["para"].strip()[1:])] = r["role"].strip()
    for i, t in enumerate(paras, 1):
        texts.setdefault(roles.get(i, "?"), []).append((tid, t))
CIT = re.compile(r"\((?:[A-Z][^()]*?\d{4}[a-z]?[^()]*)\)|\[[^\]]*\]")
def clean(t):
    t = CIT.sub("", t)
    t = re.sub(r"\b[A-ZÆØÅ][\w'’\-]+(?:,? et al\.?|(?: and | & )[A-ZÆØÅ][\w'’\-]+)?\s*(?=\(|,? \d{4})", "AUTHOR", t)
    return re.sub(r"\s+", " ", t).strip()
def first_sentence(t):
    return re.split(r"(?<=[.!?])\s+", t)[0]
STOP = set("the of and to in a is are for that as with by on be this it from or an which can at their these such its has have was were also than into when more not but".split())
out = ["# Phrasing patterns in the reference reviews", "", "Generated by `phrasing.py` from the 12 reviews joined with the role coding. Openers are the first 5 words of first sentences (author names replaced by AUTHOR); phrases are 3-grams that occur in at least 3 reviews. Nothing here is a sentence to reuse; it shows the register.", ""]
for role in ["OPEN", "CLAIM", "STUDY", "GROUP", "COMPARE", "CRITIQUE", "SYNTH", "GAP"]:
    ps = texts.get(role, [])
    if not ps: continue
    out += [f"## {role} ({len(ps)} paragraphs)", "", "**How the first sentence starts (first 5 words):**"]
    starts = Counter()
    for tid, t in ps:
        fs = clean(first_sentence(t)); w = fs.split()
        starts[" ".join(w[:5])] += 1
    for s, n in starts.most_common(12):
        out.append(f"- {s} …" + (f" (×{n})" if n > 1 else ""))
    grams = defaultdict(set)
    for tid, t in ps:
        w = [x.lower().strip(".,;:()") for x in clean(t).split()]
        for k in (3,):
            for i in range(len(w) - k + 1):
                g = w[i:i+k]
                if g[0] in STOP and g[-1] in STOP: continue
                if "author" in g: continue
                grams[" ".join(g)].add(tid)
    common = sorted(((len(v), g) for g, v in grams.items() if len(v) >= 3), reverse=True)[:20]
    out += ["", "**Phrases used in three or more reviews:** " + "; ".join(f"{g} ({n})" for n, g in common), ""]
# reporting verbs
allt = " ".join(t for ps in texts.values() for _, t in ps).lower()
verbs = ["find", "found", "show", "showed", "shown", "demonstrate", "demonstrated", "propose", "proposed", "present", "presented", "report", "reported", "argue", "argued", "suggest", "suggested", "highlight", "highlighted", "emphasize", "emphasized", "investigate", "investigated", "examine", "examined", "develop", "developed", "apply", "applied", "conclude", "concluded", "note", "noted", "observe", "observed", "address", "addressed", "consider", "considered", "assess", "assessed", "compare", "compared", "introduce", "introduced", "study", "studied", "analyze", "analyzed", "model", "modeled", "modelled", "use", "used", "implement", "implemented", "identify", "identified", "recognize", "recognized", "evaluate", "evaluated", "formulate", "formulated"]
vc = Counter({v: len(re.findall(rf"\b{v}\b", allt)) for v in verbs})
out += ["## Reporting verbs (occurrences in the 12 reviews)", "", ", ".join(f"{v} {n}" for v, n in vc.most_common(30) if n), ""]
# sentence openers overall (first word)
fw = Counter()
for ps in texts.values():
    for _, t in ps:
        for s in re.split(r"(?<=[.!?])\s+", clean(t)):
            w = s.split()
            if w: fw[w[0]] += 1
out += ["## Most common sentence-initial words", "", ", ".join(f"{w} {n}" for w, n in fw.most_common(40)), ""]
(HERE / "PHRASING.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out)[:6000])
