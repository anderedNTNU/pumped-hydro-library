"""Count candidate writing tics in the reference literature reviews and in our drafts (D-002, step 1b).

A tic goes on the banned list only if the corpus rarely uses it; what the corpus uses is allowed at
the corpus's own rate. Output: BANNED.md with rates per 1000 words for all reviews, the closest four,
the two Bore theses, and each draft given on the command line (plain-text files).

Run:  py tics.py [draft.txt ...]
"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from measure import UNITS, CLOSEST4, BORE2, SEG, in_unit, words

CANDIDATES = {
    "Inflated words": [
        "crucial", "vital", "key role", "robust", "comprehensive", "nuanced", "various", "numerous",
        "a wide range of", "landscape", "leverage", "utili[sz]e", "facilitate", "foster", "enhance",
        "ensure", "seamless", "holistic", "delve", "underscore", "highlight", "pivotal", "paramount",
        "significant(?!ly)", "significantly", "substantial", "notable", "valuable", "insight",
    ],
    "Empty openers": [
        "it is important to note", "it is worth noting", "notably", "importantly", "interestingly",
        "in this context", "in recent years", "taken together", "to this end", "as such", "in essence",
        "in particular", "in general", "overall", "in summary", "in conclusion", "building on this",
    ],
    "Signposting about the text itself": [
        "this (?:section|chapter|subsection) (?:presents|discusses|describes|reviews|examines|provides)",
        "this (?:highlights|demonstrates|illustrates|shows|underscores|suggests) (?:the|that|how)",
        "these findings (?:suggest|show|indicate|highlight)", "cannot be overstated", "the importance of",
        "the following", "as (?:discussed|mentioned|described|shown) (?:in|above|earlier|below)",
    ],
    "Patterns": [
        "not only", "but also", "rather than", "serves? as", "plays? (?:a|an) (?:\\w+ )?role",
        "a growing body of", "respectively", "both .{3,40} and", "neither .{3,40} nor",
        "—", "–(?= )", ": (?:\\(i\\)|\\(1\\)|first)", "\\(i\\)", "\\(ii\\)",
    ],
    "Hedges": [
        "may", "might", "could", "potentially", "possibly", "likely", "seems?", "appears?", "tends? to",
        "arguably", "it is possible that", "to some extent", "relatively", "somewhat", "often", "typically",
        "generally", "usually",
    ],
    "Connectors": [
        "however", "therefore", "thus", "hence", "consequently", "furthermore", "moreover", "additionally",
        "in addition", "in contrast", "similarly", "nevertheless", "nonetheless", "although", "whereas",
        "while", "accordingly", "further,", "on the other hand", "conversely", "specifically", "ultimately",
    ],
    "Reporting verbs": [
        "(?:find|found|finds)", "(?:show|showed|shows|shown)", "(?:demonstrate|demonstrated|demonstrates)",
        "(?:propose|proposed|proposes)", "(?:present|presented|presents)", "(?:report|reported|reports)",
        "(?:argue|argued|argues)", "(?:suggest|suggested|suggests)", "(?:highlight|highlighted|highlights)",
        "(?:emphasi[sz]e|emphasi[sz]ed|emphasi[sz]es)", "(?:investigate|investigated|investigates)",
        "(?:examine|examined|examines)", "(?:develop|developed|develops)", "(?:apply|applied|applies)",
        "(?:conclude|concluded|concludes)", "(?:note|noted|notes)", "(?:observe|observed|observes)",
        "(?:address|addressed|addresses)", "(?:consider|considered|considers)", "(?:assess|assessed|assesses)",
    ],
}

HERE = Path(__file__).resolve().parent


def corpus_texts():
    out = {}
    for tid, units in UNITS.items():
        recs = [json.loads(l) for l in open(SEG / f"{tid}.jsonl", encoding="utf-8")]
        out[tid] = " ".join(r["text"] for r in recs if in_unit(r, units))
    return out


def rate(pattern, text, nwords):
    n = len(re.findall(r"(?<![\w])" + pattern + r"(?![\w])", text, flags=re.I))
    return n, 1000 * n / max(1, nwords)


def main():
    texts = corpus_texts()
    nw = {t: words(x) for t, x in texts.items()}
    drafts = {}
    for p in sys.argv[1:]:
        drafts[Path(p).stem] = Path(p).read_text(encoding="utf-8", errors="ignore")
    groups = [("All (12)", list(texts)), ("Closest 4", CLOSEST4), ("Bore 2", BORE2)]
    lines = ["# Candidate writing tics: rate per 1000 words in the reference literature reviews", "",
             "Generated by `tics.py`. A pattern is a candidate for the banned list when the corpus rate is near zero; "
             "patterns the corpus uses are allowed at about the corpus rate. Case-insensitive, word-bounded regular expressions.", ""]
    hdr = "| Pattern | " + " | ".join(g for g, _ in groups) + " | " + " | ".join(drafts) + " | Verdict |"
    sep = "|---|" + "---|" * (len(groups) + len(drafts)) + "---|"
    for cat, pats in CANDIDATES.items():
        lines += [f"## {cat}", "", hdr, sep]
        for pat in pats:
            cells = []
            rates = []
            for _, ids in groups:
                text = " ".join(texts[t] for t in ids)
                n, r = rate(pat, text, sum(nw[t] for t in ids))
                cells.append(f"{r:.2f} ({n})")
                rates.append(r)
            dcells = []
            for name, dt in drafts.items():
                n, r = rate(pat, dt, words(dt))
                dcells.append(f"{r:.2f} ({n})")
            allr, c4r = rates[0], rates[1]
            if allr < 0.05 and c4r < 0.05:
                verdict = "**ban**"
            elif allr < 0.2:
                verdict = "rare: at most once per chapter"
            else:
                verdict = "allowed at corpus rate"
            lines.append(f"| `{pat}` | " + " | ".join(cells) + " | " + " | ".join(dcells) + f" | {verdict} |")
        lines.append("")
    (HERE / "BANNED.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
